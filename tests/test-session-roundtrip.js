/**
 * test-session-roundtrip.js — Case save/restore round-trip through the REAL
 * session controller.
 *
 * Unlike test-setting-persistence.js (pure predicates only), this imports the
 * actual js/app/session.js with minimal global stubs (localStorage + a
 * document whose only used surface is `getElementById(...)?.click()`), a REAL
 * createModel() from js/sim/simulation.js, and in-memory fakes for the
 * injected UI deps. It pins the most regression-prone app-layer logic:
 *   - full save() → restore() field round-trip (events, patient, modes,
 *     targets, pump concentrations)
 *   - whole-timeline bolus re-anchor when the global pump rate changed
 *     between save and restore
 *   - system rate-restore events are skipped on replay (and regenerated by
 *     manual boluses, not duplicated)
 *   - newCase() reseeds working display-unit keys from the setup defaults
 *   - persist.loadCase() rejects blobs missing patient/events
 */

const path = require('path');
const { pathToFileURL } = require('url');

let passed = 0, failed = 0;
function ok(cond, msg) {
  if (cond) { passed++; console.log(`  ✓ ${msg}`); }
  else { failed++; console.error(`  ✗ ${msg}`); }
}
function summary() {
  console.log(`\n${'='.repeat(50)}`);
  console.log(`  TOTAL: ${passed} passed, ${failed} failed`);
  console.log(`${'='.repeat(50)}\n`);
  process.exit(failed ? 1 : 0);
}

// ---- Global stubs (before any dynamic import) ----
const _store = new Map();
global.localStorage = {
  getItem: k => (_store.has(k) ? _store.get(k) : null),
  setItem: (k, v) => { _store.set(k, String(v)); },
  removeItem: k => { _store.delete(k); },
  clear: () => { _store.clear(); },
};
const _clicked = [];
global.document = {
  getElementById: (id) => ({ click() { _clicked.push(id); } }),
};

const u = (...p) => pathToFileURL(path.join(__dirname, '..', ...p)).href;

// ---- In-memory fakes for the injected deps ----
function makeFakeMode() {
  const modes = {}, ce = {}, thr = {}, exit = {};
  return {
    get: d => modes[d] || 'none',
    set: (d, m) => { modes[d] = m; },
    getCeTarget: d => ce[d] || 0,
    setCeTarget: (d, v) => { ce[d] = v; },
    getIntermittentThreshold: d => thr[d] || 0,
    setIntermittentThreshold: (d, v) => { thr[d] = v; },
    getExitCe: d => exit[d] || 0,
    setExitCe: (d, v) => { exit[d] = v; },
    refreshUI: () => {},
    reset: () => { for (const o of [modes, ce, thr, exit]) for (const k of Object.keys(o)) delete o[k]; },
  };
}
function makeFakeTimer() {
  let wallStart = null;
  return {
    getWallClock: () => wallStart ? new Date(wallStart.getTime() + 5 * 60000) : null,
    getElapsedMs: () => 5 * 60000,
    setWallClockStart: (d) => { wallStart = d; },
    _getWallStart: () => wallStart,
  };
}
function makeDeps(model, mode, timer, overrides = {}) {
  let confirmedPatient = null;
  let annotations = [];
  let selectedDrug = 'propofol';
  const calls = { initSimScreen: 0, showScreen: [], annotations: [] };
  return {
    calls,
    setSelectedDrug: d => { selectedDrug = d; },
    deps: {
      getModel: () => model,
      getConfirmedPatient: () => confirmedPatient,
      setConfirmedPatient: p => { confirmedPatient = p; },
      getSelectedDrug: () => selectedDrug,
      getAnnotations: () => annotations,
      setAnnotations: a => { annotations = Array.isArray(a) ? a : []; },
      getChart: () => null,
      destroyChart: () => {},
      timer, mode,
      settings: { reset: () => {} },
      controls: { ensureStarted: () => {}, reset: () => {}, isCaseStarted: () => true },
      setup: { reset: () => {} },
      initSimScreen: () => { calls.initSimScreen++; },
      showScreen: s => { calls.showScreen.push(s); },
      addAnnotation: t => { calls.annotations.push(t); },
      refreshChart: () => {},
      ...overrides,
    },
  };
}

const PATIENT = { age: 35, weight: 70, height: 170, male: true, opioid: false };

(async () => {
  const { createModel } = await import(u('js', 'sim', 'simulation.js'));
  const { createSession } = await import(u('js', 'app', 'session.js'));
  const persist = await import(u('js', 'ui', 'persist.js'));
  const { resetPumpSettings, getPumpSettings, DRUG_IDS } = await import(u('js', 'util', 'constants.js'));
  const { getPrefKey, getDefaultPrefKey, getAllowedUnits } = await import(u('js', 'util', 'units.js'));

  console.log('\n===== Session save/restore round-trip =====\n');

  // ---- Model surface sanity (restore() calls these unguarded) ----
  {
    const m = createModel();
    ok(typeof m.reanchorBolusDeliveries === 'function', 'model exposes reanchorBolusDeliveries');
    ok(typeof m.getAllReconciliationWindows === 'function', 'model exposes getAllReconciliationWindows');
    ok(typeof m.setReconciliationWindow === 'function', 'model exposes setReconciliationWindow');
  }

  // ---- Scenario 1: full round-trip ----
  {
    _store.clear(); resetPumpSettings();
    const model = createModel();
    const mode = makeFakeMode(), timer = makeFakeTimer();
    timer.setWallClockStart(new Date('2026-07-03T10:00:00Z'));
    const { deps } = makeDeps(model, mode, timer);
    const session = createSession(deps);

    deps.setConfirmedPatient(PATIENT);
    model.setPatient(PATIENT);
    model.planTCI('propofol', 0, 3.0);
    model.addBolus('fentanyl', 1, 0.1, 'Induction opioid', { deliveryMode: 'push' });
    mode.set('propofol', 'tci');
    mode.setCeTarget('propofol', 3.0);
    mode.setExitCe('propofol', 1.2);
    mode.setIntermittentThreshold('fentanyl', 0.8);
    deps.setAnnotations([{ id: 'note_1', timeMin: 0, time: '0:00', heading: 'Case Started', sub: '', drug: null }]);

    session.save();
    const saved = persist.loadCase();
    ok(!!saved, 'saveCase → loadCase returns a blob');
    ok(saved.v === 1 && typeof saved.savedAt === 'string', 'blob has v:1 and savedAt');
    const FIELDS = ['patient', 'events', 'bolusRateMlH', 'pumpConcentrations', 'wallClockStart',
      'modes', 'ceTargets', 'intermittentThresholds', 'exitCeTargets', 'pumpEnabled',
      'reconciliationWindows', 'reconciliationGhosts', 'annotations', 'primaryDrug'];
    ok(FIELDS.every(f => f in saved), 'blob has all 14 documented fields');

    const savedPropofolEvents = saved.events.propofol.filter(e => e.source !== 'system');

    // Wipe into a fresh session (new model, new fakes) and restore
    const model2 = createModel();
    const mode2 = makeFakeMode(), timer2 = makeFakeTimer();
    const d2 = makeDeps(model2, mode2, timer2);
    const session2 = createSession(d2.deps);
    _clicked.length = 0;
    session2.restore();

    const rp = d2.deps.getConfirmedPatient();
    ok(rp && rp.age === 35 && rp.weight === 70, 'patient restored');
    const restoredPropofol = model2.getEvents('propofol').filter(e => e.source !== 'system');
    ok(restoredPropofol.length === savedPropofolEvents.length,
      `non-system propofol events round-trip (${restoredPropofol.length}/${savedPropofolEvents.length})`);
    ok(restoredPropofol.every((e, i) =>
      Math.abs(e.time - savedPropofolEvents[i].time) < 1e-9 &&
      Math.abs(e.value - savedPropofolEvents[i].value) < 1e-9 &&
      e.type === savedPropofolEvents[i].type), 'propofol event times/values/types identical');
    ok(model2.getEvents('fentanyl').some(e => e.type === 'bolus' && e.deliveryMode === 'push'),
      'fentanyl push bolus restored');
    ok(mode2.get('propofol') === 'tci' && mode2.getCeTarget('propofol') === 3.0, 'mode + Ce target restored');
    ok(mode2.getExitCe('propofol') === 1.2, 'emergence (exitCe) target restored');
    ok(mode2.getIntermittentThreshold('fentanyl') === 0.8, 'redose threshold restored');
    ok(getPumpSettings('propofol').concentration === saved.pumpConcentrations.propofol,
      'per-case pump concentration reapplied');
    ok(timer2._getWallStart() instanceof Date, 'wall clock start restored');
    ok(d2.deps.getAnnotations().length >= 1, 'annotations restored');
    ok(_clicked.includes('drug-propofol'), 'saved primaryDrug card re-selected on restore');
  }

  // ---- Scenario 2: re-anchor under a changed global pump rate ----
  {
    _store.clear(); resetPumpSettings();
    const model = createModel();
    const mode = makeFakeMode(), timer = makeFakeTimer();
    const { deps } = makeDeps(model, mode, timer);
    const session = createSession(deps);
    deps.setConfirmedPatient(PATIENT);
    model.setPatient(PATIENT);
    model.planTCI('propofol', 0, 3.0);   // planned at default 750 mL/h
    session.save();
    const saved = persist.loadCase();
    const bolus = saved.events.propofol.find(e => e.type === 'bolus');
    ok(saved.bolusRateMlH === 750, 'case saved with the 750 mL/h pump rate');

    // Simulate the global pump rate having been corrected to 500 mL/h since
    _store.set('tci-pump-max-rate', '500');
    const model2 = createModel();
    const d2 = makeDeps(model2, makeFakeMode(), makeFakeTimer());
    const session2 = createSession(d2.deps);
    session2.restore();

    const conc = getPumpSettings('propofol').concentration; // per-case, 10
    const expectedEnd = Math.max(0.05, (bolus.value / conc) / 500 * 60);
    const firstStep = model2.getEvents('propofol')
      .filter(e => e.type === 'rate' && e.time > 0 && e.source !== 'system')
      .sort((a, b) => a.time - b.time)[0];
    ok(!!firstStep && Math.abs(firstStep.time - expectedEnd) < 1e-6,
      `plan's first rate step re-anchored to the 500 mL/h bolus end (${firstStep && firstStep.time.toFixed(5)} vs ${expectedEnd.toFixed(5)})`);
  }

  // ---- Scenario 3: system events skipped on replay, regenerated not duplicated ----
  {
    _store.clear(); resetPumpSettings();
    const model = createModel();
    const { deps } = makeDeps(model, makeFakeMode(), makeFakeTimer());
    const session = createSession(deps);
    deps.setConfirmedPatient(PATIENT);
    model.setPatient(PATIENT);
    model.addRate('propofol', 0, 6.0, 'Manual infusion');
    model.addBolus('propofol', 2, 50, 'Manual bolus'); // generates one system rate-restore
    const sysBefore = model.getEvents('propofol').filter(e => e.source === 'system').length;
    ok(sysBefore === 1, 'manual bolus generated exactly one system rate-restore');
    session.save();

    const model2 = createModel();
    const d2 = makeDeps(model2, makeFakeMode(), makeFakeTimer());
    createSession(d2.deps).restore();
    const ev2 = model2.getEvents('propofol');
    ok(ev2.filter(e => e.source === 'system').length === 1,
      'restore regenerates the system restore once (skip-on-replay + addBolus recreate)');
    ok(ev2.some(e => e.type === 'rate' && e.source !== 'system') &&
       ev2.some(e => e.type === 'bolus'), 'manual rate + bolus survive restore');
  }

  // ---- Scenario 4: newCase() reseeds working unit keys from setup defaults ----
  {
    _store.clear(); resetPumpSettings();
    const workKey = getPrefKey('propofol', 'rate');
    const defKey = getDefaultPrefKey('propofol', 'rate');
    const allowed = getAllowedUnits('propofol', 'rate');
    ok(Array.isArray(allowed) && allowed.length >= 2, 'propofol rate has ≥2 allowed units');
    const defUnit = allowed[0], midCaseUnit = allowed[1];
    _store.set(defKey, defUnit);
    _store.set(workKey, midCaseUnit); // a mid-case swap
    const model = createModel();
    const { deps } = makeDeps(model, makeFakeMode(), makeFakeTimer());
    createSession(deps).newCase();
    ok(_store.get(workKey) === defUnit,
      `newCase reseeds working key from default (${midCaseUnit} → ${defUnit})`);
    ok(_store.get(defKey) === defUnit, 'setup default key untouched by newCase');
  }

  // ---- Scenario 5: loadCase rejects malformed blobs ----
  {
    _store.clear();
    _store.set('tci-sim-last-case', JSON.stringify({ v: 1, savedAt: 'x', events: {} }));
    ok(persist.loadCase() === null, 'loadCase → null when patient missing');
    _store.set('tci-sim-last-case', JSON.stringify({ v: 1, savedAt: 'x', patient: PATIENT }));
    ok(persist.loadCase() === null, 'loadCase → null when events missing');
    _store.set('tci-sim-last-case', 'not json{');
    ok(persist.loadCase() === null, 'loadCase → null on corrupt JSON');
    _store.set('tci-sim-last-case', JSON.stringify({ v: 1, savedAt: 'x', patient: PATIENT, events: {} }));
    ok(persist.loadCase() !== null, 'loadCase accepts a minimal valid blob');
    _store.set('tci-sim-last-case', JSON.stringify({ v: 2, savedAt: 'x', patient: PATIENT, events: {} }));
    ok(persist.loadCase() === null, 'loadCase → null for a newer schema version (v:2)');
    ok(persist.CASE_SCHEMA_VERSION === 1, 'CASE_SCHEMA_VERSION is 1');
  }

  // ---- Scenario 6: DRUG_IDS-generalized restore (no hardcoded drug list) ----
  {
    _store.clear(); resetPumpSettings();
    const model = createModel();
    const { deps } = makeDeps(model, makeFakeMode(), makeFakeTimer());
    const session = createSession(deps);
    deps.setConfirmedPatient(PATIENT);
    model.setPatient(PATIENT);
    model.addBolus('ketamine', 0, 30, 'Analgesia', { deliveryMode: 'push' });
    session.save();
    const saved = persist.loadCase();
    ok(DRUG_IDS.every(d => typeof saved.pumpConcentrations[d] === 'number'),
      'pumpConcentrations saved for every DRUG_IDS drug');

    const model2 = createModel();
    const d2 = makeDeps(model2, makeFakeMode(), makeFakeTimer());
    createSession(d2.deps).restore();
    ok(DRUG_IDS.every(d => getPumpSettings(d).concentration === saved.pumpConcentrations[d]),
      'every drug\'s per-case concentration reapplied on restore');
  }

  summary();
})().catch(err => {
  console.error('FATAL:', err);
  failed++;
  summary();
});
